package me.anno.chemistry

/**
 * when it is solid, how does it behave?
 * */
enum class SolidType {
    POWDER,          // flour, cocoa
    CRYSTAL,         // sugar, ice
    GEL,             // jam, custard
    FOAM,            // whipped cream, meringue
    SQUEEZABLE,      // butter, dough
    FIBROUS,         // strawberry, banana
    BRITTLE_COOKIE,  // baked cookie
    SOFT_COOKIE,     // soft baked goods
    RUBBERY,         // overcooked egg
    HARD,            // candy, frozen chocolate
}
